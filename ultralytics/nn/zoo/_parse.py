def parse(m, f, n, args, ch, ctx):
    """Return (m, c2, args, n) for zoo layer `m` (class, or backbone factory); ctx holds the scale constants.

    ctx keys: nc, width, max_channels, scale, threshold, reg_max, end2end, legacy (legacy is updated in place). A
    backbone factory is called here (its width_list needs the built module), so the returned m is an instance.
    """
    name, width, max_ch, scale = m.__name__, ctx["width"], ctx["max_channels"], ctx["scale"] or ""

    def scaled(c):
        return make_divisible(min(c, max_ch) * width, 8)

    c2 = ch[-1]  # old parse_model left c2 from the previous layer in branches that do not set it
    if name in BACKBONES:
        m = m(*args)
        return m, m.width_list, args, 1
    if name == FEATURE:  # args = [k]: k-th of the 4 deepest outputs of the backbone at layer f
        widths = ch[f]
        k = args[0] + len(widths) - 4
        return m, widths[k], [k], 1
    if name == "PST" and isinstance(f, list):
        c2 = scaled(args[0]) if args[0] != ctx["nc"] else args[0]
        return m, c2, [ch[f[0]], ch[f[1]], c2, *args[1:]], n
    if name in BASE:
        c1, c2 = ch[f], scaled(args[0])
        if name == "ConvTranspose2d" and len(args) > 5 and args[5] == args[0]:  # depthwise (groups == c2): scale groups
            args[5] = c2
        args = [c1, c2, *args[1:]]
        if name in REPEAT:
            args.insert(2, n)
            n = 1
        if name in C3K_MLX:
            ctx["legacy"] = False
            if scale in "mlx":
                args[3:4] = [True]
        if name == "A2C2fMoE":
            ctx["legacy"] = False
        if name == "MobileNetV3_BLOCK" and len(args) > 3 and args[3] is not None:  # expansion scales like c2
            args[3] = scaled(args[3])
        return m, c2, args, n
    if name == "RepViTBlock":  # (in1, inp, hidden_dim, oup, ...): the block requires hidden_dim == 2 * inp
        return m, ch[f], [ch[f], ch[f], 2 * ch[f], ch[f], *args], n
    if name == "PatchMerging":  # Swin merging always doubles the width, max_channels or not
        return m, 2 * ch[f], [ch[f], 2 * ch[f]], n
    if name == "SwinStage":  # (dim, c2, depth, heads, window): keeps its width
        return m, ch[f], [ch[f], ch[f], *args[1:]], n
    if name in SAME_CH:
        return m, ch[f], [ch[f], *args], n
    if name in ATTN_C1:
        return m, scaled(args[0]) if args[0] != ctx["nc"] else args[0], [ch[f], *args[1:]], n
    if name in CONCAT:
        return m, sum(ch[x] for x in f), args, n
    if name in HEADS:
        args.extend([ctx["reg_max"], ctx["end2end"], [ch[x] for x in f]])
        if name in {"MAFSegment", "ISegment"}:
            args[2] = scaled(args[2])
        m.legacy = ctx["legacy"]
        return m, c2, args, n
    if name == "Bi_FPN":
        return m, c2, [len(f)], n
    if name == "Light_HGBlock":
        c2 = args[1]
        args = [ch[f], args[0], c2, *args[2:]]
        args.insert(4, n)
        return m, c2, args, 1
    if name in {"EMCAD_block", "MultiOrderGatedAggregation"}:
        return m, c2, [ch[f]], n
    if name == "iRMB":
        return m, c2, [ch[f], ch[f]], n
    if name == "LSKblock":
        return m, c2, [ch[f], *args], n
    if name == "AVG":
        return m, ch[f], args, n
    if name == "LCA_DynamicTanh_Concat":  # fuses to `out` channels via conv_down; dim = the wider input
        c2 = scaled(args[1])
        return m, c2, [max(ch[x] for x in f), c2, *args[2:]], n
    if name == "DASI":
        f_high, f_low, f_mid = f
        c2 = scaled(args[3])
        return m, c2, [ch[f_high], ch[f_mid], ch[f_low], c2], n
    if name == "IEMA":
        c2 = scaled(args[0]) if args[0] != ctx["nc"] else args[0]
        return m, c2, [ch[f], c2, 16], n
    if name == "HyperComputeModule":
        c2 = scaled(args[0])
        return m, c2, [ch[f], c2, ctx["threshold"]], n
    if name == "ADD":
        return m, sum(ch[x] for x in f) // 2, args, n
    if name == "SimFusion_3in":
        c2 = scaled(args[0]) if args[0] != ctx["nc"] else args[0]
        return m, c2, [[ch[x] for x in f], c2], n
    if name == "IFM":
        return m, sum(args[0]), [ch[f], *args], n
    if name == "DySample":
        return m, ch[f], [ch[f], *args], n
    if name == "InjectionMultiSum_Auto_pool":
        return m, args[0], [ch[f[0]], *args], n
    if name == "PyramidPoolAgg":
        return m, args[0], [sum(ch[x] for x in f), *args], n
    if name == "TopBasicLayer":
        return m, sum(args[1]), args, n
    if name in {"Shortcut", "FullPAD_Tunnel"}:
        return m, ch[f[0]], args, n
    if name == "ReOrg":
        return m, ch[f] * 4, args, n
    if name == "Transpose":
        c2 = scaled(args[0])
        return m, c2, [ch[f], c2, *args[1:]], n
    if name in {"MobileOne", "MobileOne_origin", "MobileOneBlock_origin"}:  # n is built inside the module
        c2 = scaled(args[0])
        return m, c2, [ch[f], c2, n, *args[1:]], 1
    if name == "Add":
        return m, ch[f[-1]], args, n
    if name == "ScalSeq":
        c2 = make_divisible(args[0] * width, 8)
        return m, c2, [[ch[x] for x in f], c2], n
    if name == "attention_model":
        return m, c2, [ch[f[-1]]], n
    if name == "SCConv":
        return m, args[0], [ch[f], *args], n
    if name == "SDFM":
        return m, ch[f[1]], [ch[f[1]], *args], n
    if name == "ChannelAggregationFFN":
        return m, c2, [ch[f], c2], n
    if name in {"CSPResNet_CBS", "CSPResNet", "ConvBNLayer", "ResSPP"}:
        return m, args[1], args, n
    if name == "HorBlock":  # HorBlock(dim) keeps its channels; n repeats are n stacked blocks
        return m, ch[f], [ch[f], *args[1:]], n
    if name == "SNI":  # only upsamples: channels pass through
        return m, ch[f], [ch[f], ch[f], args[1]], n
    if name == "HyperACE":
        ctx["legacy"] = False
        c2 = scaled(args[0])
        he = int(args[1] * 0.5) if scale in "n" else int(args[1] * 1.5) if scale in "x" else args[1]
        args = [ch[f[1]], c2, n, he, *args[2:]]
        if scale in "lx":
            args.append(False)
        return m, c2, args, 1
    if name == "F2SoftHG":  # adjust_channels: fused input is 4C, or 3C when max_channels caps P5
        c1 = ch[f[1]]
        return m, c1, [c1, c1, *args, sum(ch[x] for x in f) == 4 * c1], n
    if name == "DownsampleConv":
        c1 = ch[f]
        return (m, c1, [c1, False], n) if scale in "lx" else (m, c1 * 2, [c1], n)
    if name == "ShapeAlignConv":  # match P5, which is 2x P4 unless max_channels caps it
        c2 = ch[f] * 2 if 2 * ch[f] <= max_ch * width else ch[f]
        return m, c2, [ch[f], c2 != ch[f]], n
    if name == "MergeConv":
        return m, ch[f[0]], [ch[f[0]]], n
    if name == "HRIF":
        c2 = scaled(args[0])
        return m, c2, [[ch[x] for x in f], c2, *args[1:]], n
    if name in {"MSCAM", "MSCAMv2", "MSCAMv3", "MSCAMv4", "MSCAMv5"}:
        return m, ch[f], [ch[f], args[0]], n
    return m, ch[f], args, n  # the fork's default: channels pass through
