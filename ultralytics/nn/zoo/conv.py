class BatchChannelNorm(nn.Module):
    def __init__(self, num_channels, epsilon=1e-5, momentum=0.9):
        super(BatchChannelNorm, self).__init__()
        self.num_channels = num_channels
        self.epsilon = epsilon
        self.momentum = momentum

        # 1. 使用 PyTorch 內建的 BatchNorm2d
        # affine=False 表示這個層只做標準化，不做後續的 gamma/beta 縮放平移
        # 因為我們會在後面用自己的 gamma/beta 統一處理
        self.batch_norm = nn.BatchNorm2d(self.num_channels, eps=self.epsilon, momentum=self.momentum, affine=False)

        # LayerNorm 將在 forward 方法中用 F.layer_norm 實現，因此這裡不需要定義

        # 用於混合 Batch Norm 和 Layer Norm 的可學習參數 rho
        # 原名 BCN_var 容易誤解，改為 rho 或 mixing_param 更常見
        self.rho = nn.Parameter(torch.ones(self.num_channels))

        # 用於最終縮放和平移的 Gamma 和 Beta
        self.gamma = nn.Parameter(torch.ones(self.num_channels))
        self.beta = nn.Parameter(torch.zeros(self.num_channels))

    def forward(self, x):
        # 確保輸入維度正確
        assert len(x.shape) == 4  # (N, C, H, W)
        assert x.shape[1] == self.num_channels

        # 計算 Batch Normalization 的輸出
        X_bn = self.batch_norm(x)

        # 2. 使用 PyTorch 內建的 functional layer_norm
        # 對每個樣本的所有通道和空間維度 (C, H, W) 進行標準化
        # normalized_shape=x.shape[1:] 表示對維度 1, 2, 3 進行標準化
        Y_ln = F.layer_norm(x, normalized_shape=x.shape[1:], eps=self.epsilon)

        # 確保 self.rho 的維度可以廣播
        # [1, C, 1, 1] 以便和 [N, C, H, W] 的張量運算
        rho_reshaped = self.rho.view(1, self.num_channels, 1, 1)

        # 混合 Batch Norm 和 Layer Norm 的結果
        # 使用 sigmoid 函數將 rho 限制在 0 和 1 之間，使其更像一個混合權重
        mixing_weights = torch.sigmoid(rho_reshaped)
        out = mixing_weights * X_bn + (1 - mixing_weights) * Y_ln

        # 進行最終的縮放和平移
        out = self.gamma.view(1, self.num_channels, 1, 1) * out + self.beta.view(1, self.num_channels, 1, 1)
        return out


class DynamicTanh(nn.Module):
    def __init__(self, normalized_shape, data_format="channels_first", alpha_init_value=0.5):
        super().__init__()
        self.normalized_shape = normalized_shape
        self.alpha_init_value = alpha_init_value
        self.data_format = data_format

        self.alpha = nn.Parameter(torch.ones(1) * alpha_init_value)
        self.weight = nn.Parameter(torch.ones(normalized_shape))
        self.bias = nn.Parameter(torch.zeros(normalized_shape))

    def forward(self, x):
        x = torch.tanh(self.alpha * x)
        if self.data_format == "channels_last":
            x = x * self.weight + self.bias
        else:
            x = x * self.weight[:, None, None] + self.bias[:, None, None]
        return x


class Conv_BCN(nn.Module):
    """Standard convolution with args(ch_in, ch_out, kernel, stride, padding, groups, dilation, activation)."""

    default_act = nn.SiLU()  # default activation

    def __init__(self, c1, c2, k=1, s=1, p=None, g=1, d=1, act=True):
        """Initialize Conv layer with given arguments including activation."""
        super().__init__()
        self.conv = nn.Conv2d(c1, c2, k, s, autopad(k, p, d), groups=g, dilation=d, bias=False)
        self.bn = BatchChannelNorm(c2)
        self.act = self.default_act if act is True else act if isinstance(act, nn.Module) else nn.Identity()

    def forward(self, x):
        """Apply convolution, batch normalization and activation to input tensor."""
        return self.act(self.bn(self.conv(x)))

    def forward_fuse(self, x):
        """Perform transposed convolution of 2D data."""
        return self.act(self.conv(x))


class FDConv_cfg(nn.Module):
    """Standard convolution Block with Batch Norm and Activation, using FDConv."""

    default_act = nn.SiLU()  # Default activation

    def __init__(self, c1, c2, k=1, s=1, freq_groups=1, p=None, g=1, d=1, act=True):
        """
        Args:
            c1 (int): input channels
            c2 (int): output channels
            k (int): kernel size
            s (int): stride
            p (int or None): padding; if None uses autopad
            g (int): groups
            d (int): dilation
            act (bool or nn.Module): activation to use (True→default_act, False→Identity, or custom)
        """
        super().__init__()
        padding = autopad(k, p, d)
        # replace nn.Conv2d with FDConv
        self.conv = FDConv(
            in_channels=c1,
            out_channels=c2,
            kernel_size=k,
            stride=s,
            n_freq_groups=freq_groups,
            padding=padding,
            dilation=d,
            groups=g,
            bias=False,
        )
        self.bn = nn.BatchNorm2d(c2)
        self.act = self.default_act if act is True else (act if isinstance(act, nn.Module) else nn.Identity())

    def forward(self, x):
        """Conv → BatchNorm → Activation"""
        x = self.conv(x)
        x = self.bn(x)
        return self.act(x)

    def forward_fuse(self, x):
        """Conv only (for fused deployments) → Activation"""
        return self.act(self.conv(x))


